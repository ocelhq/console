import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { readMigrationFiles } from "drizzle-orm/migrator";

const migrations = readMigrationFiles({ migrationsFolder: "drizzle" });
const out = "src/migrations.gen.ts";

writeFileSync(
  out,
  `// Generated by \`bun run db:generate\` from drizzle/. Do not edit.
import type { MigrationMeta } from "drizzle-orm/migrator";

export const migrations: MigrationMeta[] = ${JSON.stringify(migrations, null, 2)};
`,
);
execFileSync("biome", ["format", "--write", out], { stdio: "inherit" });
